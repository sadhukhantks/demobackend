-- EJM wages data collection (ported from EMPMILL12/sls for the EJM Wages Process screen).
-- Structure taken from sls.tbl_ejm_wages_data_collection (the newest variant, with the
-- prev_cuml_* cumulative columns EMPMILL12 lacks).
-- Target: dev3
CREATE TABLE IF NOT EXISTS tbl_ejm_wages_data_collection (
  data_collection_id int NOT NULL AUTO_INCREMENT,
  date_from date DEFAULT NULL,
  date_to date DEFAULT NULL,
  eb_id int DEFAULT NULL,
  dept_code char(3) DEFAULT NULL,
  occu_code char(3) DEFAULT NULL,
  shift char(1) DEFAULT NULL,
  t_p char(1) DEFAULT NULL,
  mc_nos varchar(30) DEFAULT NULL,
  working_hours decimal(8,2) DEFAULT '0.00',
  ot_hours decimal(8,2) DEFAULT '0.00',
  ns_hours decimal(8,2) DEFAULT '0.00',
  fest_hours decimal(8,2) DEFAULT '0.00',
  stl_days decimal(8,2) DEFAULT '0.00',
  working_hours_eff decimal(8,2) DEFAULT '0.00',
  ot_hours_eff decimal(8,2) DEFAULT '0.00',
  production decimal(8,2) DEFAULT '0.00',
  prod_basic decimal(8,2) DEFAULT '0.00',
  time_basic decimal(8,2) DEFAULT '0.00',
  puja_advance decimal(8,2) DEFAULT '0.00',
  ot_advance decimal(8,2) DEFAULT '0.00',
  stl_advance decimal(8,2) DEFAULT '0.00',
  co_loan decimal(8,2) DEFAULT '0.00',
  misc_earn decimal(8,2) DEFAULT '0.00',
  misc_ded decimal(8,2) DEFAULT '0.00',
  misc_ot_earn decimal(8,2) DEFAULT '0.00',
  misc_ot_ded decimal(8,2) DEFAULT '0.00',
  update_for varchar(5) DEFAULT NULL,
  pay_scheme_id int DEFAULT '0',
  is_active int NOT NULL DEFAULT '1',
  eff_code int DEFAULT NULL,
  installment_advance int DEFAULT '0',
  inst_advance_date date DEFAULT NULL,
  ot_ns_hours decimal(6,2) DEFAULT '0.00',
  updt_from varchar(5) DEFAULT NULL,
  act_eff decimal(7,2) DEFAULT NULL,
  payschme_id int DEFAULT NULL,
  prev_cuml_pf_contribution int DEFAULT '0',
  prev_cuml_w_days decimal(8,2) DEFAULT '0.00',
  prev_cuml_pf_gross decimal(8,2) DEFAULT '0.00',
  prev_cuml_bonus_gross varchar(100) DEFAULT '0',
  prev_cuml_fpf_contribution int DEFAULT NULL,
  PRIMARY KEY (data_collection_id),
  KEY idx_date_range (date_from, date_to),
  KEY idx_eb (eb_id),
  KEY idx_dept (dept_code),
  KEY idx_occu (occu_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
