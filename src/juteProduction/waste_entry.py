def _validate_area_branch(db: Session, dept_id: int, branch_id: int) -> None:
    """The area's branch must be the department's own branch.

    Doubles as the dept-exists guard. Without it an area could be filed under
    branch A with a department from branch B — the entry picker reads areas by
    (co_id, branch_id) and validates them by dept_id, so such a row would be
    invisible in the UI yet still pass the write guard.

    A NULL dept_mst.branch_id is tolerated (the column is nullable), in which
    case the caller's branch stands.
    """
    dept_branch_id = _dept_branch_id(db, dept_id)
    if dept_branch_id is not None and int(dept_branch_id) != int(branch_id):
        raise HTTPException(
            status_code=400,
            detail="dept_id belongs to a different branch than the submitted branch_id",
        )


def _clean_area_name(area_name: str) -> str:
    name = (area_name or "").strip()
    if not name:
        raise HTTPException(status_code=400, detail="area_name is required")
    if len(name) > 100:
        raise HTTPException(
            status_code=400, detail="area_name cannot exceed 100 characters"
        )
    return name


def _reject_duplicate_area(
    db: Session,
    branch_id: int,
    dept_id: int,
    area_name: str,
    exclude_id: Optional[int],
) -> None:
    """Answer the UNIQUE key with a 400 instead of a raw MySQL 1062 -> 500."""
    row = db.execute(
        get_wastage_area_duplicate_query(),
        {
            "branch_id": int(branch_id),
            "dept_id": int(dept_id),
            "area_name": area_name,
            "exclude_id": exclude_id,
        },
    ).fetchone()
    if row:
        raise HTTPException(status_code=400, detail=AREA_DUP_MSG)


