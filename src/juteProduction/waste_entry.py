def _validate_waste_rate(body, db: Session, co_id: int) -> float:
    """Shared create/edit guards: waste item, non-negative rate, sane window.

    The item guard is the same one the waste ENTRY uses, so a rate can only ever
    be filed against an item the entry page can actually book — no orphan rates
    for ordinary stock items.
    """
    _validate_waste_item(db, body.item_id, co_id)
    try:
        rate = float(body.rate)
    except (TypeError, ValueError):
        raise HTTPException(status_code=400, detail=RATE_NEGATIVE_MSG)
    if rate < 0:
        raise HTTPException(status_code=400, detail=RATE_NEGATIVE_MSG)
    if body.valid_to is not None and body.valid_to < body.valid_from:
        raise HTTPException(status_code=400, detail=RATE_WINDOW_MSG)
    return rate


@router.get("/rate_list")
def rate_list(
    request: Request,
    db: Session = Depends(get_tenant_db),
    token_data: dict = Depends(get_current_user_with_refresh),
):
    """Waste valuation rates for the company, optionally narrowed to one branch.

    Company-wide rows (branch_id NULL) are returned under a branch filter too —
    they are in force for that branch, so hiding them would misrepresent the
    rate actually applied on the issue page.
    """
    co_id = _require_co_id(request)
    branch_id = _optional_branch_id(request)
    try:
        rows = db.execute(
            get_waste_rate_list_query(), {"co_id": co_id, "branch_id": branch_id}
        ).fetchall()
        data = [
            _serialize_dates(dict(r._mapping), keys=("valid_from", "valid_to"))
            for r in rows
        ]
        for row in data:
            row["rate"] = _f(row.get("rate"))
        return {"data": data}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


