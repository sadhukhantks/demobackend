@router.get("/entry_create_setup")
def entry_create_setup(
    request: Request,
    db: Session = Depends(get_tenant_db),
    token_data: dict = Depends(get_current_user_with_refresh),
):
    """Dropdown payload: spells (with working_hours), departments, all active
    wastage areas and machines for the branch (both carrying dept_id for the
    client-side cascade), and the waste items (item type 3, company-scoped)
    (SPEC §6)."""
    co_id = _require_co_id(request)
    branch_id = _optional_branch_id(request)
    try:
        spells = []
        seen = set()
        for r in db.execute(
            get_waste_spells_query(), {"branch_id": branch_id}
        ).fetchall():
            m = dict(r._mapping)
            code = m["spell_code"]
            if code in seen:
                continue
            seen.add(code)
            spells.append(
                {
                    "spell_id": int(m["spell_id"]),
                    "spell_code": code,
                    "spell_name": m["spell_name"],
                    "working_hours": _f(m.get("working_hours")),
                }
            )

        departments = []
        for r in db.execute(
            get_waste_departments_query(), {"branch_id": branch_id}
        ).fetchall():
            m = dict(r._mapping)
            departments.append(
                {
                    "dept_id": m["dept_id"],
                    "dept_desc": m["dept_desc"],
                    "branch_id": m["branch_id"],
                }
            )

        machines = []
        for r in db.execute(
            get_waste_machines_query(), {"branch_id": branch_id}
        ).fetchall():
            m = dict(r._mapping)
            machines.append(
                {
                    "machine_id": m["machine_id"],
                    "machine_name": m["machine_name"],
                    "mech_code": m["mech_code"],
                    "machine_type_id": m["machine_type_id"],
                    "machine_type_name": m["machine_type_name"],
                    "dept_id": m["dept_id"],
                    "dept_name": m["dept_name"],
                    "branch_id": m["branch_id"],
                }
            )

        wastage_areas = []
        for r in db.execute(
            get_waste_areas_query(), {"co_id": co_id, "branch_id": branch_id}
        ).fetchall():
            m = dict(r._mapping)
            wastage_areas.append(
                {
                    "wastage_area_id": m["wastage_area_id"],
                    "area_name": m["area_name"],
                    "dept_id": m["dept_id"],
                    "branch_id": m["branch_id"],
                }
            )

        waste_items = []
        for r in db.execute(
            get_waste_items_query(),
            {"co_id": co_id, "item_type_id": JUTE_WASTAGE_ITEM_TYPE_ID},
        ).fetchall():
            m = dict(r._mapping)
            waste_items.append(
                {
                    "item_id": m["item_id"],
                    "item_name": m["item_name"],
                    "item_code": m["item_code"],
                }
            )

        return {
            "data": {
                "spells": spells,
                "departments": departments,
                "wastage_areas": wastage_areas,
                "machines": machines,
                "waste_items": waste_items,
            }
        }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@router.get("/entries_by_date")
def entries_by_date(
    request: Request,
    db: Session = Depends(get_tenant_db),
    token_data: dict = Depends(get_current_user_with_refresh),
):
    """Day grid: one row per active waste event for the date/branch, with
    dept_name / machine_name / spell_code resolved for display."""
    co_id = _require_co_id(request)
    branch_id = _optional_branch_id(request)
    d = request.query_params.get("tran_date")
    if not d:
        raise HTTPException(status_code=400, detail="tran_date is required")
    try:
        d_val = date.fromisoformat(d)
        rows = db.execute(
            get_waste_by_date_query(),
            {"co_id": co_id, "tran_date": d_val, "branch_id": branch_id},
        ).fetchall()
        data = []
        for r in rows:
            row = dict(r._mapping)
            if row.get("waste_qty") is not None:
                row["waste_qty"] = float(row["waste_qty"])
            _serialize_dates(row)
            data.append(row)
        return {"data": data}
    except HTTPException:
        raise
    except ValueError:
        raise HTTPException(status_code=400, detail="Invalid tran_date format")
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


