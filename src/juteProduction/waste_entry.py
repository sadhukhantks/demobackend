def _require_co_id(request: Request) -> int:
    raw = request.query_params.get("co_id")
    if not raw:
        raise HTTPException(status_code=400, detail="co_id is required")
    try:
        return int(raw)
    except ValueError:
        raise HTTPException(status_code=400, detail="Invalid co_id")


def _optional_branch_id(request: Request) -> Optional[int]:
    raw = request.query_params.get("branch_id")
    if not raw:
        return None
    try:
        return int(raw)
    except ValueError:
        raise HTTPException(status_code=400, detail="Invalid branch_id")


def _f(v, default: float = 0.0) -> float:
    """Cast a possibly-None / Decimal value to float."""
    return default if v is None else float(v)


def _serialize_dates(row: dict, keys=("tran_date",)) -> dict:
    for k in keys:
        if row.get(k) is not None:
            row[k] = str(row[k])
    return row


def _validate_waste_item(db: Session, item_id: int, co_id: int) -> int:
    """The waste type must be an active 'jute wastage' item of this company.

    One query covers existence, active, item type 3 and company scope — unknown
    item, deactivated item, wrong item type and another company's item all
    collapse to the same 400.
    """
    row = db.execute(
        verify_waste_item_query(),
        {
            "item_id": int(item_id),
            "co_id": int(co_id),
            "item_type_id": JUTE_WASTAGE_ITEM_TYPE_ID,
        },
    ).fetchone()
    if not row:
        raise HTTPException(status_code=400, detail=BAD_ITEM_MSG)
    return int(item_id)


def _validate_qty(waste_qty) -> float:
    """Gate 0 < waste_qty <= WASTE_QTY_MAX (the DECIMAL(10,3) column width).

    Rejecting the over-wide value here means the API answers 400 instead of
    letting MySQL truncate or error out mid-insert (SPEC §2).
    """
    try:
        qty = float(waste_qty)
    except (TypeError, ValueError):
        raise HTTPException(status_code=400, detail=QTY_GATE_MSG)
    if qty <= 0 or qty > WASTE_QTY_MAX:
        raise HTTPException(status_code=400, detail=QTY_GATE_MSG)
    return qty


def _validate_tran_date(tran_date: date) -> date:
    """tran_date must not be in the future (SPEC §2)."""
    if tran_date > date.today():
        raise HTTPException(status_code=400, detail=FUTURE_DATE_MSG)
    return tran_date


def _validate_spell(db: Session, spell_id: int) -> int:
    """spell_id must exist in spell_mst (400 otherwise)."""
    row = db.execute(
        verify_spell_exists_query(), {"spell_id": int(spell_id)}
    ).fetchone()
    if not row:
        raise HTTPException(status_code=400, detail=UNKNOWN_SPELL_MSG)
    return int(spell_id)


def _dept_branch_id(db: Session, dept_id: int) -> Optional[int]:
    """Resolve the department's branch, doubling as the dept-exists guard.

    No row -> unknown dept_id (400). A row with branch_id NULL is legitimate:
    dept_mst.branch_id is nullable, which is why reads COALESCE (SPEC §10).
    """
    row = db.execute(
        derive_branch_for_dept_query(), {"dept_id": int(dept_id)}
    ).fetchone()
    if not row:
        raise HTTPException(status_code=400, detail=UNKNOWN_DEPT_MSG)
    return row.branch_id


def _validate_area_in_dept(
    db: Session, wastage_area_id: int, dept_id: int, co_id: int
) -> int:
    """Wastage-area guard: active area of this company AND of the given dept.

    Unknown area, deactivated area, another company's area and an area of a
    different department all collapse to the same 400 — the same shape as the
    machine guard.
    """
    row = db.execute(
        verify_area_in_dept_query(),
        {
            "wastage_area_id": int(wastage_area_id),
            "dept_id": int(dept_id),
            "co_id": int(co_id),
        },
    ).fetchone()
    if not row:
        raise HTTPException(status_code=400, detail=AREA_DEPT_MSG)
    return int(wastage_area_id)


def _validate_machine_in_dept(db: Session, machine_id: int, dept_id: int) -> int:
    """Machine/department guard (SPEC §10).

    Unknown machine, inactive machine, and machine-in-another-department all
    collapse to the same 400.
    """
    row = db.execute(
        verify_machine_in_dept_query(),
        {"machine_id": int(machine_id), "dept_id": int(dept_id)},
    ).fetchone()
    if not row:
        raise HTTPException(status_code=400, detail=MACHINE_DEPT_MSG)
    return int(machine_id)


