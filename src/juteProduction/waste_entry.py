"""Waste Entry endpoints (jute production module).

A daily process-loss event log under the prefix ``/api/juteWasteProd``. Each row
records an item-tagged waste quantity (kg) generated by a DEPARTMENT on a (date,
spell), optionally attributed to a machine. Unlike Stoppage Hours, dept_id IS
stored (waste is a departmental measure and is often booked in bulk with no
single machine responsible), so machine_id is the optional field here. The waste
type is an ITEM: ``item_id`` references item_mst and is restricted to items whose
group has item_type_id = 3 ('jute wastage'). The table is an append/soft-delete
log: many rows per (dept, date, spell, item) are expected and there is NO unique
constraint.

Persona: Portal (get_tenant_db + get_current_user_with_refresh, {"data": ...}
responses, soft delete via active = 0, NO approval workflow). Conventions mirror
stoppage_entry.py: _require_co_id / _optional_branch_id / _f / _serialize_dates
helpers, and the try/except (GET: HTTPException raise / ValueError 400 /
Exception 500; POST/PUT/DELETE: db.rollback() then raise / 500) pattern.

Five entry endpoints (SPEC §6): entry_create_setup, entry_create,
entries_by_date, entry_edit, entry_delete. Validation (SPEC §2 + §10): item_id
an active item of item type 3 in the caller's company, 0 < waste_qty <=
WASTE_QTY_MAX, tran_date not in the future, spell_id present in spell_mst,
dept_id present in dept_mst, a REQUIRED wastage_area_id whose
wastage_area_mst.dept_id equals dept_id, and — when a machine is supplied —
machine_mst.dept_id = dept_id AND machine_mst.active = 1. branch_id is derived
from dept_mst when the client omits it.

The same router also carries two small masters — same module, same prefix, so
neither needs a separate registration:
  * Wastage Area (area_list / area_create / area_edit), which feeds the entry
    page's Area dropdown;
  * Waste Rate (rate_list / rate_create / rate_edit), the effective-dated
    valuation rate per QUINTAL that prices a waste line on the Jute Issue page.
    Waste booked here becomes issuable stock (vw_jute_waste_stock_outstanding),
    and waste has no purchase rate of its own, so this master is the only source
    of a waste line's issue value.
"""

