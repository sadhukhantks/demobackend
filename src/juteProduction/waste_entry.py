@router.post("/entry_create")
def entry_create(
    body: WasteEntryCreate,
    db: Session = Depends(get_tenant_db),
    token_data: dict = Depends(get_current_user_with_refresh),
):
    """Insert one waste event.

    Cheap in-memory gates run first (waste_qty, tran_date), then the DB-backed
    ones (waste item is an active type-3 item of this company, spell exists,
    dept exists — which also yields the derived branch — and the
    machine/department guard). branch_id falls back to dept_mst.branch_id
    whenever the client omits it (SPEC §10).
    """
    try:
        waste_qty = _validate_qty(body.waste_qty)
        tran_date = _validate_tran_date(body.tran_date)

        item_id = _validate_waste_item(db, body.item_id, body.co_id)
        spell_id = _validate_spell(db, body.spell_id)
        dept_branch_id = _dept_branch_id(db, body.dept_id)
        wastage_area_id = _validate_area_in_dept(
            db, body.wastage_area_id, body.dept_id, body.co_id
        )

        machine_id = None
        if body.machine_id is not None:
            machine_id = _validate_machine_in_dept(db, body.machine_id, body.dept_id)

        branch_id = body.branch_id if body.branch_id is not None else dept_branch_id

        user_id = token_data.get("user_id")
        result = db.execute(
            insert_waste_row_query(),
            {
                "co_id": int(body.co_id),
                "branch_id": branch_id,
                "tran_date": tran_date,
                "spell_id": spell_id,
                "dept_id": int(body.dept_id),
                "wastage_area_id": wastage_area_id,
                "machine_id": machine_id,
                "item_id": item_id,
                "waste_qty": waste_qty,
                "remarks": body.remarks,
                "updated_by": user_id,
            },
        )
        db.commit()
        return {"data": {"waste_entry_id": result.lastrowid}}
    except HTTPException:
        db.rollback()
        raise
    except Exception as e:
        db.rollback()
        raise HTTPException(status_code=500, detail=str(e))


@router.put("/entry_edit/{waste_entry_id}")
def entry_edit(
    waste_entry_id: int,
    body: WasteEntryUpdate,
    request: Request,
    db: Session = Depends(get_tenant_db),
    token_data: dict = Depends(get_current_user_with_refresh),
):
    """Edit spell_id / wastage_area_id / machine_id / item_id / waste_qty / remarks.

    dept_id and tran_date are immutable (delete + re-add to move a row). Every
    supplied field is re-validated; area and machine changes are re-checked
    against the row's EXISTING dept_id so the §10 guard cannot be sidestepped by
    editing.

    Requires co_id: the row is located by (waste_entry_id, co_id), so a row
    belonging to another company reads as 404 rather than being editable.
    """
    try:
        co_id = _require_co_id(request)
        existing = db.execute(
            get_waste_active_by_id_query(), {"id": waste_entry_id, "co_id": co_id}
        ).fetchone()
        if not existing:
            raise HTTPException(status_code=404, detail=NOT_FOUND_MSG)

        new_item_id = (
            _validate_waste_item(db, body.item_id, co_id)
            if body.item_id is not None
            else existing.item_id
        )
        new_qty = (
            _validate_qty(body.waste_qty)
            if body.waste_qty is not None
            else _f(existing.waste_qty)
        )
        new_spell_id = (
            _validate_spell(db, body.spell_id)
            if body.spell_id is not None
            else existing.spell_id
        )
        # Area is mandatory. A row booked before the master existed carries NULL,
        # so an edit that leaves the field out cannot silently keep it empty —
        # the operator must pick one to save the row at all.
        new_wastage_area_id = (
            _validate_area_in_dept(db, body.wastage_area_id, existing.dept_id, co_id)
            if body.wastage_area_id is not None
            else existing.wastage_area_id
        )
        if new_wastage_area_id is None:
            raise HTTPException(status_code=400, detail=AREA_REQUIRED_MSG)

        new_machine_id = existing.machine_id
        if body.machine_id is not None:
            new_machine_id = _validate_machine_in_dept(
                db, body.machine_id, existing.dept_id
            )
        new_remarks = body.remarks if body.remarks is not None else existing.remarks

        user_id = token_data.get("user_id")
        db.execute(
            update_waste_row_query(),
            {
                "id": waste_entry_id,
                "co_id": co_id,
                "spell_id": new_spell_id,
                "wastage_area_id": new_wastage_area_id,
                "machine_id": new_machine_id,
                "item_id": new_item_id,
                "waste_qty": new_qty,
                "remarks": new_remarks,
                "updated_by": user_id,
            },
        )
        db.commit()
        return {"data": {"waste_entry_id": waste_entry_id}}
    except HTTPException:
        db.rollback()
        raise
    except Exception as e:
        db.rollback()
        raise HTTPException(status_code=500, detail=str(e))


