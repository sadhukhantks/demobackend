@router.post("/area_create")
def area_create(
    body: WastageAreaCreate,
    db: Session = Depends(get_tenant_db),
    token_data: dict = Depends(get_current_user_with_refresh),
):
    """Create one wastage area.

    dept_id must exist and live in the submitted branch, and the name must be
    unique within (branch, department).
    """
    try:
        area_name = _clean_area_name(body.area_name)
        _validate_area_branch(db, body.dept_id, body.branch_id)
        _reject_duplicate_area(db, body.branch_id, body.dept_id, area_name, None)

        result = db.execute(
            insert_wastage_area_query(),
            {
                "co_id": int(body.co_id),
                "branch_id": int(body.branch_id),
                "dept_id": int(body.dept_id),
                "area_name": area_name,
                "active": 1 if int(body.active) else 0,
                "updated_by": token_data.get("user_id"),
            },
        )
        db.commit()
        return {"data": {"wastage_area_id": result.lastrowid}}
    except HTTPException:
        db.rollback()
        raise
    except Exception as e:
        db.rollback()
        raise HTTPException(status_code=500, detail=str(e))


