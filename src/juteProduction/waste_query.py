# Validation / derivation builders
# =============================================================================


def verify_waste_item_query():
    """Write guard for the waste type: one query, three checks.

    Returns a row only when the item exists AND is active AND its group is of
    item type 3 ('jute wastage') AND that group belongs to the caller's company
    — so an unknown item, a deactivated one, an item of the wrong type, and
    another company's item all collapse to the same 400 in the router.
    """
    return text(
        """
        SELECT im.item_id
        FROM item_mst im
        INNER JOIN item_grp_mst ig ON ig.item_grp_id = im.item_grp_id
        WHERE im.item_id = :item_id
          AND im.active = 1
          AND ig.item_type_id = :item_type_id
          AND ig.co_id = :co_id
        """
    )


def derive_branch_for_dept_query():
    """Branch derivation on INSERT: dept -> branch (SPEC §10).

    Doubles as the ``dept_id must exist in dept_mst`` guard (SPEC §2): no row
    means an unknown department. A row with a NULL branch_id is legitimate —
    dept_mst.branch_id is itself nullable, which is exactly why reads COALESCE.
    """
    return text(
        """
        SELECT d.dept_id, d.branch_id
        FROM dept_mst d
        WHERE d.dept_id = :dept_id
        """
    )


def verify_spell_exists_query():
    """``spell_id must exist in spell_mst`` guard (SPEC §2).

    No status guard by design: the row stores spell_id, so a retired spell still
    resolves for display — existence is all this validates.
    """
    return text(
        """
        SELECT spell_id
        FROM spell_mst
        WHERE spell_id = :spell_id
        """
    )


def verify_area_in_dept_query():
    """Wastage-area guard: area must be active, in this company AND in the dept.

    Unknown area, deactivated area, another company's area and an area of a
    different department all collapse to the same 400 in the router — the same
    one-query/four-checks shape as verify_machine_in_dept_query.
    """
    return text(
        """
        SELECT a.wastage_area_id
        FROM wastage_area_mst a
        WHERE a.wastage_area_id = :wastage_area_id
          AND a.dept_id = :dept_id
          AND a.co_id = :co_id
          AND a.active = 1
        """
    )


def verify_machine_in_dept_query():
    """Machine/department guard (SPEC §10): machine must be active AND in dept.

    Returns no row when the machine is unknown, inactive, or belongs to another
    department — all three collapse to the same 400 in the router.
    """
    return text(
        """
        SELECT m.machine_id
        FROM machine_mst m
        WHERE m.machine_id = :machine_id
          AND m.dept_id = :dept_id
          AND m.active = 1
        """
    )


