def insert_waste_row_query():
    """Insert one waste event (active = 1). No unique key — this is a log."""
    return text(
        """
        INSERT INTO jute_prod_waste_entry
            (co_id, branch_id, tran_date, spell_id, dept_id, wastage_area_id,
             machine_id, item_id, waste_qty, remarks, active, updated_by)
        VALUES
            (:co_id, :branch_id, :tran_date, :spell_id, :dept_id, :wastage_area_id,
             :machine_id, :item_id, :waste_qty, :remarks, 1, :updated_by)
        """
    )


def get_waste_active_by_id_query():
    """One active waste row by id, scoped to the caller's company.

    The `co_id` predicate is deliberate and load-bearing: a tenant DB holds
    every company's rows, so matching on the primary key alone would let a user
    scoped to company A read (and via the edit / delete guards, mutate)
    company B's row by guessing an id. Callers MUST pass the request's co_id.
    """
    return text(
        """
        SELECT waste_entry_id, co_id, branch_id, tran_date, spell_id, dept_id,
               wastage_area_id, machine_id, item_id, waste_qty, remarks
        FROM jute_prod_waste_entry
        WHERE waste_entry_id = :id AND co_id = :co_id AND active = 1
        """
    )


def update_waste_row_query():
    """Edit spell_id / wastage_area_id / machine_id / item_id / waste_qty / remarks.

    dept_id and tran_date are immutable (mirrors the stoppage precedent, where
    the branch-driving field is not editable) — delete + re-add to move a row to
    another department or date, which keeps the branch derivation clean.
    """
    return text(
        """
        UPDATE jute_prod_waste_entry
        SET spell_id        = :spell_id,
            wastage_area_id = :wastage_area_id,
            machine_id      = :machine_id,
            item_id         = :item_id,
            waste_qty       = :waste_qty,
            remarks         = :remarks,
            updated_by      = :updated_by
        WHERE waste_entry_id = :id AND co_id = :co_id AND active = 1
        """
    )


def soft_delete_waste_row_query():
    """Soft delete (active = 0), scoped to the caller's company.

    Carries the same `co_id` predicate as the read guard so the scope check
    cannot be lost if the two ever drift apart.
    """
    return text(
        """
        UPDATE jute_prod_waste_entry
        SET active = 0, updated_by = :updated_by
        WHERE waste_entry_id = :id AND co_id = :co_id AND active = 1
        """
    )


