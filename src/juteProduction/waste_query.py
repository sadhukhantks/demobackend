def get_wastage_area_list_query():
    """Master grid: every area of the company (optionally one branch), active or not.

    Inactive rows ARE returned — this is a maintenance screen, so the operator
    must be able to see and re-enable what they disabled. dept_mst / branch_mst
    are LEFT joins purely for display labels.
    """
    return text(
        """
        SELECT a.wastage_area_id, a.co_id, a.branch_id, a.dept_id, a.area_name,
               a.active, d.dept_desc AS dept_name, b.branch_name
        FROM wastage_area_mst a
        LEFT JOIN dept_mst d ON d.dept_id = a.dept_id
        LEFT JOIN branch_mst b ON b.branch_id = a.branch_id
        WHERE a.co_id = :co_id
          AND (:branch_id IS NULL OR a.branch_id = :branch_id)
        ORDER BY d.dept_desc, a.area_name
        """
    )


def get_wastage_area_duplicate_query():
    """Duplicate guard for (branch_id, dept_id, area_name) — the table's UNIQUE key.

    `:exclude_id` is the row being edited (pass None on create) so an edit that
    leaves the name alone does not collide with itself. Answering 400 here beats
    surfacing a raw MySQL 1062 through the 500 handler.
    """
    return text(
        """
        SELECT wastage_area_id
        FROM wastage_area_mst
        WHERE branch_id = :branch_id
          AND dept_id = :dept_id
          AND area_name = :area_name
          AND (:exclude_id IS NULL OR wastage_area_id <> :exclude_id)
        """
    )


def get_wastage_area_by_id_query():
    """One area by id, scoped to the caller's company (404 guard for edit)."""
    return text(
        """
        SELECT wastage_area_id, co_id, branch_id, dept_id, area_name, active
        FROM wastage_area_mst
        WHERE wastage_area_id = :wastage_area_id AND co_id = :co_id
        """
    )


def insert_wastage_area_query():
    return text(
        """
        INSERT INTO wastage_area_mst
            (co_id, branch_id, dept_id, area_name, active, updated_by)
        VALUES
            (:co_id, :branch_id, :dept_id, :area_name, :active, :updated_by)
        """
    )


def update_wastage_area_query():
    """Edit every field including the branch/department the area hangs off.

    Re-parenting an area is allowed (a typo at creation is otherwise
    unfixable); historical waste rows keep pointing at the same area row, and
    the entry-side guard only ever checks the CURRENT dept on new writes.
    """
    return text(
        """
        UPDATE wastage_area_mst
        SET branch_id  = :branch_id,
            dept_id    = :dept_id,
            area_name  = :area_name,
            active     = :active,
            updated_by = :updated_by
        WHERE wastage_area_id = :wastage_area_id AND co_id = :co_id
        """
    )


