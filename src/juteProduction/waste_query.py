def get_waste_rate_list_query():
    """Master grid: every waste rate of the company (optionally one branch).

    Like the wastage-area grid this is a maintenance screen, so inactive rows
    ARE returned. ``:branch_id`` matches company-wide rows (branch_id IS NULL)
    as well as the branch's own — a company-wide rate applies to every branch,
    so hiding it while a branch filter is on would misrepresent what is in
    force. item_mst is a LEFT join purely for the display label.
    """
    return text(
        """
        SELECT r.waste_rate_id, r.co_id, r.branch_id, r.item_id, r.rate,
               r.valid_from, r.valid_to, r.active,
               im.item_name, im.item_code, b.branch_name
        FROM jute_waste_rate_mst r
        LEFT JOIN item_mst im ON im.item_id = r.item_id
        LEFT JOIN branch_mst b ON b.branch_id = r.branch_id
        WHERE r.co_id = :co_id
          AND (:branch_id IS NULL OR r.branch_id = :branch_id OR r.branch_id IS NULL)
        ORDER BY im.item_name, r.valid_from DESC, r.waste_rate_id DESC
        """
    )


def get_waste_rate_by_id_query():
    """One rate row by id, scoped to the caller's company (404 guard for edit)."""
    return text(
        """
        SELECT waste_rate_id, co_id, branch_id, item_id, rate,
               valid_from, valid_to, active
        FROM jute_waste_rate_mst
        WHERE waste_rate_id = :waste_rate_id AND co_id = :co_id
        """
    )


def insert_waste_rate_query():
    return text(
        """
        INSERT INTO jute_waste_rate_mst
            (co_id, branch_id, item_id, rate, valid_from, valid_to, active, updated_by)
        VALUES
            (:co_id, :branch_id, :item_id, :rate, :valid_from, :valid_to, :active, :updated_by)
        """
    )


def update_waste_rate_query():
    """Edit every field including the item the rate hangs off.

    Re-pointing a rate at another item is allowed (a wrong pick at creation is
    otherwise unfixable). Already-saved issue lines keep the issue_value that
    was computed at save time — repricing history is deliberately NOT done.
    """
    return text(
        """
        UPDATE jute_waste_rate_mst
        SET branch_id  = :branch_id,
            item_id    = :item_id,
            rate       = :rate,
            valid_from = :valid_from,
            valid_to   = :valid_to,
            active     = :active,
            updated_by = :updated_by
        WHERE waste_rate_id = :waste_rate_id AND co_id = :co_id
        """
    )


