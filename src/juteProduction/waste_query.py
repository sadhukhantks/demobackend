"""Raw SQL builders for the Jute Production — Waste Entry module.

Waste Entry is a daily process-loss event log (see the waste-entry SPEC). Each
row records an item-tagged waste quantity (kg) generated by a DEPARTMENT on a
(date, spell), optionally attributed to a machine. Unlike Stoppage Hours, the
department IS stored (``dept_id`` NOT NULL) because waste is fundamentally a
departmental measure and is frequently booked with no single machine
responsible; ``machine_id`` is therefore nullable.

branch_id is derived from ``dept_mst.branch_id`` on insert (SPEC §10) and reads
are tolerant of legacy NULLs via ``COALESCE(w.branch_id, d.branch_id)``.

Conventions mirror stoppage_query.py / winding_query.py: sqlalchemy.text() with
named binds, the ``:x IS NULL OR ...`` optional-filter idiom, and spell_id (INT)
joined to spell_mst (which keys activity by ``status``, NOT ``active``).

Notes on the master joins:
* ``dept_mst`` has NO ``active`` column (see src/models/mst.py DeptMst) — the
  department list is gated by branch only.
* ``machine_mst`` has no ``branch_id`` of its own; branch travels via dept_mst.
* The setup machine query exposes ALL active machines for the branch together
  with their ``dept_id`` so the FE can cascade Department -> Machine client-side
  without a second round trip (SPEC §6).
* The waste type is an ITEM (``item_id``), not an app enum: the picker and the
  write guard both restrict to items whose GROUP has ``item_type_id = 3``
  ('jute wastage'). Company scope rides on ``item_grp_mst.co_id`` — item_mst has
  no co_id of its own. ``item_grp_mst.active`` is a VARCHAR of mixed values and
  is deliberately NOT filtered, matching the sibling item pickers
  (beaming_query.get_beaming_cloth_items_query, finishing_query).
"""

from sqlalchemy import text


# =============================================================================
# Setup / lookup builders
# =============================================================================


def get_waste_spells_query():
    """Active spells with working hours from spell_mst (branch scoped via shift).

    Trimmed copy of stoppage_query.get_stoppage_spells_query. spell_mst keys
    activity by ``status`` (1 = active), NOT an ``active`` column; the parent
    shift is likewise filtered by status. Callers de-duplicate by spell_code
    (some tenants carry a duplicate spell_code under a second branch's shift).
    """
    return text(
        """
        SELECT sp.spell_id, sp.spell_code, sp.spell_name, sp.working_hours
        FROM spell_mst sp
        INNER JOIN shift_mst sh ON sh.shift_id = sp.shift_id
        WHERE sp.status = 1
          AND sh.status = 1
          AND (:branch_id IS NULL OR sh.branch_id = :branch_id)
        ORDER BY sp.starting_time
        """
    )


def get_waste_departments_query():
    """Departments for the branch (dept_mst has no ``active`` column).

    Waste is a departmental measure, so the department dropdown is the primary
    selector on the page — it is NOT derived from the machine.
    """
    return text(
        """
        SELECT d.dept_id, d.dept_desc, d.branch_id
        FROM dept_mst d
        WHERE (:branch_id IS NULL OR d.branch_id = :branch_id)
        ORDER BY d.dept_desc
        """
    )


def get_waste_machines_query():
    """ALL active machines for the branch with their dept_id (cascade source).

    Returned for the whole branch in one shot so the FE can filter by the
    selected department client-side (SPEC §6). branch_id is the department's
    branch (machine_mst has no branch_id of its own).
    """
    return text(
        """
        SELECT
            m.machine_id,
            m.machine_name,
            m.mech_code,
            m.machine_type_id,
            mt.machine_type_name,
            d.dept_id,
            d.dept_desc AS dept_name,
            d.branch_id
        FROM machine_mst m
        INNER JOIN machine_type_mst mt ON mt.machine_type_id = m.machine_type_id
        INNER JOIN dept_mst d ON d.dept_id = m.dept_id
        WHERE m.active = 1
          AND mt.active = 1
          AND (:branch_id IS NULL OR d.branch_id = :branch_id)
        ORDER BY d.dept_desc, m.machine_name
        """
    )


def get_waste_areas_query():
    """ALL active wastage areas for the branch with their dept_id (cascade source).

    Same shape as get_waste_machines_query: the whole branch comes back in one
    shot so the FE filters by the selected department client-side. co_id is
    matched too — the master is created per (company, branch).
    """
    return text(
        """
        SELECT a.wastage_area_id, a.area_name, a.dept_id, a.branch_id
        FROM wastage_area_mst a
        WHERE a.active = 1
          AND a.co_id = :co_id
          AND (:branch_id IS NULL OR a.branch_id = :branch_id)
        ORDER BY a.area_name
        """
    )


def get_waste_items_query():
    """Waste-type picker: active items of item type 3 ('jute wastage').

    item_mst carries no co_id — company scope lives on item_grp_mst.co_id, which
    is also where item_type_id hangs (same shape as the beaming / finishing item
    pickers). item_grp_mst.active is a nullable VARCHAR of inconsistent values,
    so only im.active is gated.
    """
    return text(
        """
        SELECT im.item_id, im.item_name, im.item_code
        FROM item_mst im
        INNER JOIN item_grp_mst ig ON ig.item_grp_id = im.item_grp_id
        WHERE im.active = 1
          AND ig.item_type_id = :item_type_id
          AND ig.co_id = :co_id
        ORDER BY im.item_name
        """
    )


