def get_waste_by_date_query():
    """Day-grid read: resolve dept_desc / area_name / machine_name / spell_code / item label.

    dept_mst is an INNER join (dept_id is NOT NULL); wastage_area_mst,
    machine_mst, spell_mst and item_mst are LEFT joins because machine
    attribution is optional, rows booked before the area master existed carry a
    NULL wastage_area_id, and a spell or waste item may since have been retired
    — the row must still display.
    COALESCE(w.branch_id, d.branch_id) tolerates a legacy NULL branch_id on the
    row (SPEC §10).
    """
    return text(
        """
        SELECT
            w.waste_entry_id,
            w.tran_date,
            w.spell_id,
            sp.spell_code,
            sp.spell_name,
            w.dept_id,
            d.dept_desc AS dept_name,
            w.wastage_area_id,
            wa.area_name,
            w.machine_id,
            m.machine_name,
            w.item_id,
            im.item_name,
            im.item_code,
            w.waste_qty,
            w.remarks,
            COALESCE(w.branch_id, d.branch_id) AS branch_id
        FROM jute_prod_waste_entry w
        INNER JOIN dept_mst d ON d.dept_id = w.dept_id
        LEFT JOIN wastage_area_mst wa ON wa.wastage_area_id = w.wastage_area_id
        LEFT JOIN machine_mst m ON m.machine_id = w.machine_id
        LEFT JOIN spell_mst sp ON sp.spell_id = w.spell_id
        LEFT JOIN item_mst im ON im.item_id = w.item_id
        WHERE w.active = 1
          AND w.co_id = :co_id
          AND w.tran_date = :tran_date
          AND (:branch_id IS NULL OR COALESCE(w.branch_id, d.branch_id) = :branch_id)
        ORDER BY d.dept_desc, im.item_name, w.waste_entry_id
        """
    )
